class Solution(object):
    def maximumScore(self, grid):
        """
        :type grid: List[List[int]]
        :rtype: int
        """


        n = len(grid)
        # prefix sum calculation
        col_prefix = [[0] * (n + 1) for _ in range(n)]
        for j in range(n):
            for i in range(n):
                col_prefix[j][i + 1] = col_prefix[j][i] + grid[i][j]


        # helper: determining the heigh/value of a column value
        def col_sum(j, lo, hi):
            if j < 0 or j >= n or lo >= hi:
                return 0
            return col_prefix[j][hi] - col_prefix[j][lo]

        NEG = float('-inf') # holder

        dp = {}
        dp[(0, 0)] = 0

        for i in range(n):
            new_dp = {}
            for (h_prev, h_pprev), base in dp.items():
                if base == NEG:
                    continue
                for h_curr in range(n + 1):
                    if h_curr > h_prev:
                        #core col i-1 cells [max(h_prev,h_pprev)..h_curr-1]
                        #       (avoid cells already scored by col i-2)
                        if i == 0:
                            score = 0
                        else:
                            lo = max(h_prev, h_pprev)
                            score = col_sum(i - 1, lo, h_curr)
                    else:
                        # score col i white cells [h_curr..h_prev-1] adj to black col i-1
                        score = col_sum(i, h_curr, h_prev)

                    val = base + score
                    key = (h_curr, h_prev)
                    if new_dp.get(key, NEG) < val:
                        new_dp[key] = val

            dp = new_dp

        return max(dp.values()) if dp else 0


