class Solution(object):
    def maximumScore(self, grid):
        """
        :type grid: List[List[int]]
        :rtype: int
        """
        n = len(grid)

        col_prefix = [[0] * (n + 1) for _ in range(n)]
        for j in range(n):
            for i in range(n):
                col_prefix[j][i + 1] = col_prefix[j][i] + grid[i][j]

        def col_sum(j, lo, hi):
            if j < 0 or j >= n or lo >= hi:
                return 0
            return col_prefix[j][hi] - col_prefix[j][lo]

        NEG = float('-inf')

        # dp[h_prev][h_pprev] = best score with last col height h_prev, before-last h_pprev
        dp = [[NEG] * (n + 1) for _ in range(n + 1)]
        dp[0][0] = 0

        for i in range(n):
            new_dp = [[NEG] * (n + 1) for _ in range(n + 1)]

            # Precompute for each h_prev:
            # 1. best_free[h_prev] = max over ALL h_pprev of dp[h_prev][h_pprev]
            #    (used when h_curr <= h_prev: score doesn't depend on h_pprev)
            # 2. max_below[h_prev] = max over h_pprev < h_prev of dp[h_prev][h_pprev]
            #    (used when h_curr > h_prev and h_pprev < h_prev: lo = h_prev)
            # 3. suf[h_prev][k] = max over h_pprev >= k of (dp[h_prev][h_pprev] - col_prefix[i-1][h_pprev])
            #    (used when h_curr > h_prev and h_pprev >= h_prev: lo = h_pprev)
            #    score = suf[h_prev][h_prev] + col_prefix[i-1][h_curr]

            best_free = [NEG] * (n + 1)
            max_below = [NEG] * (n + 1)

            # suffix max of (dp[h_prev][h_pprev] - col_prefix[i-1][h_pprev]) for h_pprev >= threshold
            # suf[h_prev][k] = max over h_pprev in [k..n]
            # We only need suf[h_prev][h_prev], so build per h_prev
            suf_at_hprev = [NEG] * (n + 1)  # suf_at_hprev[h_prev] = suf[h_prev][h_prev]

            for h_prev in range(n + 1):
                row = dp[h_prev]
                # best_free
                best_free[h_prev] = max(row)
                # max_below: max over h_pprev in [0..h_prev-1]
                mb = NEG
                for k in range(h_prev):
                    if row[k] > mb:
                        mb = row[k]
                max_below[h_prev] = mb
                # suf from h_prev upward
                if i > 0:
                    s = NEG
                    # suffix from n down to h_prev
                    for k in range(n, h_prev - 1, -1):
                        if row[k] != NEG:
                            v = row[k] - col_prefix[i-1][k]
                            if v > s:
                                s = v
                    suf_at_hprev[h_prev] = s

            for h_prev in range(n + 1):
                for h_curr in range(n + 1):
                    if h_curr <= h_prev:
                        # score col i white cells [h_curr..h_prev-1], no h_pprev dependency
                        base = best_free[h_prev]
                        if base == NEG:
                            continue
                        score = col_sum(i, h_curr, h_prev)
                        val = base + score
                        if val > new_dp[h_curr][h_prev]:
                            new_dp[h_curr][h_prev] = val

                    else:
                        # h_curr > h_prev
                        if i == 0:
                            # no col i-1 exists, score = 0
                            base = dp[h_prev][0] if h_prev == 0 else NEG
                            if base != NEG and base > new_dp[h_curr][h_prev]:
                                new_dp[h_curr][h_prev] = base
                            continue

                        best = NEG

                        # Case A: h_pprev < h_prev → lo = h_prev
                        # score = col_sum(i-1, h_prev, h_curr)
                        if max_below[h_prev] != NEG:
                            v = max_below[h_prev] + col_sum(i - 1, h_prev, h_curr)
                            if v > best:
                                best = v

                        # Case B: h_pprev >= h_prev → lo = h_pprev
                        # score = col_prefix[i-1][h_curr] - col_prefix[i-1][h_pprev]
                        # val = dp[h_prev][h_pprev] - col_prefix[i-1][h_pprev] + col_prefix[i-1][h_curr]
                        # = suf_at_hprev[h_prev] + col_prefix[i-1][h_curr]
                        if suf_at_hprev[h_prev] != NEG:
                            v = suf_at_hprev[h_prev] + col_prefix[i - 1][h_curr]
                            if v > best:
                                best = v

                        if best > new_dp[h_curr][h_prev]:
                            new_dp[h_curr][h_prev] = best

            dp = new_dp

        # Optimisation: last column should be h=0 (fully white) or h=n (fully black)
        # as it doesn't affect future columns — only extreme values can be optimal
        ans = 0
        for h_pprev in range(n + 1):
            for h in [0, n]:
                v = dp[h][h_pprev]
                if v != NEG and v > ans:
                    ans = v
        return ans
    
