import bisect

class Solution(object):
    def maxWalls(self, robots, distance, walls):
        """
        :type robots: List[int]
        :type distance: List[int]
        :type walls: List[int]
        :rtype: int
        """
        # sort walls and robots
        # Pairing distance with robots is essential
        robot_data = sorted(zip(robots, distance))
        walls.sort()

        #define the max range left and right for each robot (distance between robot pairs)
        num_robots = len(robots)
        total_destroyed = 0
        last_wall_idx = 0 # Pointer to the first wall that hasn't been destroyed yet

        #use the distance seporation to determine the actual ranges
        for i in range(num_robots):
            curr_pos, curr_dist = robot_data[i]

            # left neighbour boundary
            if i == 0:
                left_limit = float('-inf')
            else:
                left_limit = robot_data[i-1][0]
            
            # right neighbour boundary
            if i == num_robots - 1:
                right_limit = float('inf')
            else:
                right_limit = robot_data[i+1][0]
            
            # get the closest location (either another robot or range runs out)
            actual_left = max(left_limit, curr_pos - curr_dist)
            actual_right = min(right_limit, curr_pos + curr_dist)
            
            # Binary search to find the number of walls
            # We use lo=last_wall_idx to ensure we never look at a wall 
            # that was already claimed by a previous robot.
            idx_start = bisect.bisect_left(walls, actual_left, lo=last_wall_idx)
            idx_end = bisect.bisect_right(walls, actual_right, lo=idx_start)
            
            # keep a running total of unique walls distroyed
            count = idx_end - idx_start
            total_destroyed += count
            
            # Update the pointer to the end of this robot's harvest
            last_wall_idx = idx_end

        return total_destroyed
    






