from bisect import bisect_left, bisect_right

class Solution(object):
    def maxWalls(self, robots, distance, walls):
        """
        :type robots: List[int]
        :type distance: List[int]
        :type walls: List[int]
        :rtype: int
        """
        bots = sorted(zip(robots, distance), key=lambda x: x[0])
        sorted_walls = sorted(walls)
        n = len(bots)

        def count_walls(lo, hi):
            if lo > hi:
                return 0
            return bisect_right(sorted_walls, hi) - bisect_left(sorted_walls, lo)

        def count_walls_exclusive(lo, hi, exclude_lo, exclude_hi):
            """Count walls in [lo,hi] but NOT in [exclude_lo, exclude_hi]."""
            if lo > hi:
                return 0
            total = count_walls(lo, hi)
            if exclude_lo > hi or exclude_hi < lo:
                return total
            overlap_lo = max(lo, exclude_lo)
            overlap_hi = min(hi, exclude_hi)
            return total - count_walls(overlap_lo, overlap_hi)

        # eft and right ranges for each robot
        ranges = []
        for i, (pos, dist) in enumerate(bots):
            left_lo = pos - dist if i == 0 else max(pos - dist, bots[i-1][0] + 1)
            left_hi = pos
            right_lo = pos
            right_hi = pos + dist if i == n-1 else min(pos + dist, bots[i+1][0] - 1)
            ranges.append((left_lo, left_hi, right_lo, right_hi))

        # DP: dp[direction] = max walls if robot i fires in that direction        
        if n == 0:
            return 0

        ll0, lh0, rl0, rh0 = ranges[0]
        # dp[0] = fires left, dp[1] = fires right
        dp = [count_walls(ll0, lh0), count_walls(rl0, rh0)]

        for i in range(1, n):
            ll, lh, rl, rh = ranges[i]
            prev_ll, prev_lh, prev_rl, prev_rh = ranges[i-1]

            walls_i_left = count_walls(ll, lh)
            walls_i_right = count_walls(rl, rh)

            # Overlap between current robot's LEFT range and previous robot's RIGHT range
            # (these share the gap between the two robots)
            overlap_lo = max(ll, prev_rl)
            overlap_hi = min(lh, prev_rh)
            overlap = count_walls(overlap_lo, overlap_hi) if overlap_lo <= overlap_hi else 0

            new_dp = [0, 0]

            # Current fires LEFT
            # - prev fired LEFT: no overlap possible (prev right range doesn't touch current left range)
            new_dp[0] = max(new_dp[0], dp[0] + walls_i_left)
            # - prev fired RIGHT: subtract overlap (walls counted in both)
            new_dp[0] = max(new_dp[0], dp[1] + walls_i_left - overlap)

            # Current fires RIGHT
            # - prev fired LEFT: no overlap
            new_dp[1] = max(new_dp[1], dp[0] + walls_i_right)
            # - prev fired RIGHT: no overlap (prev right and current right don't overlap)
            new_dp[1] = max(new_dp[1], dp[1] + walls_i_right)

            dp = new_dp

        return max(dp)