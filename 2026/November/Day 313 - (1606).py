import heapq

class Solution(object):
    def busiestServers(self, k, arrival, load):
        """
        :type k: int
        :type arrival: List[int]
        :type load: List[int]
        :rtype: List[int]
        """
        # Each free server is stored as a "virtual id": a number whose
        # remainder mod k is the real server id (virtual % k == server).
        # Rule: a free server's virtual id is the smallest number >= i
        # (the current request index) that is congruent to its id mod k.
        # So the smallest virtual id in the heap is exactly the first free
        # server at or after i % k, wrapping around. No ordered set needed.

        available = list(range(k))   # all free at start; 0..k-1 is already a valid heap
        busy = []                    # min-heap of (end_time, real_server_id)
        res = [0] * k                # requests handled per server

        for i, a in enumerate(arrival):
            # Free every server that has finished by time a (<= matters).
            while busy and busy[0][0] <= a:
                _, x = heapq.heappop(busy)
                # Smallest number >= i with remainder x mod k:
                #   i + ((x - i) % k)
                # Python's % is never negative, so this lies in [i, i+k-1].
                heapq.heappush(available, i + (x - i) % k)

            if available:            # if empty, the request is dropped
                j = heapq.heappop(available) % k   # back to the real server id
                heapq.heappush(busy, (a + load[i], j))
                res[j] += 1

        best = max(res)
        return [s for s in range(k) if res[s] == best]