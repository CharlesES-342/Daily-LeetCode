class Solution(object):
    def minimumChanges(self, s, k):
        """
        :type s: str
        :type k: int
        :rtype: int
        """
        # only need to check upto half (as this is where the valid divisors will be at most)
        # find valid divisors

        # for each divisor, check the arrays from elemnents in the list of divisor + y*divisor where y increases for each step:
        #   this will mean each element is only looked at once (O(n))

        # start from the largest divisor first ??

        n = len(s)
        INF = float('inf')

        # precompute proper divisors for every possible substring length.
        # only upto L//2
        divs = [[] for _ in range(n + 1)]
        for d in range(1, n // 2 + 1):
            # d is a proper divisor of 2d, 3d, 4d, ... (never of d itself)
            for L in range(2 * d, n + 1, d):
                divs[L].append(d)

        # cost[i][j] = minimum changes to turn s[i..j] (inclusive) into a semi-palindrome.
        # Single characters stay INF because no valid d exists for length 1.
        cost = [[INF] * n for _ in range(n)]
        for i in range(n):
            for j in range(i + 1, n):
                L = j - i + 1 # length of this substring
                best = INF

                # try every proper divisor and keep the cheapest.
                # (cost is NOT monotonic in d, so "largest first" isn't safe)
                for d in divs[L]:
                    cnt = L // d # number of elements in each group
                    c = 0 # changes needed for this d

                    # split the substring into d groups: indices i+r, i+r+d, i+r+2d, ...
                    # each group must itself be a palindrome
                    for r in range(d):
                        lo = i + r # first element of group
                        hi = i + r + (cnt - 1) * d # last element of group

                        # compare mirrored pairs, moving inwards in steps of d
                        while lo < hi:
                            if s[lo] != s[hi]:
                                c += 1 # one change fixes a mismatched pair
                            lo += d
                            hi -= d

                    best = min(best, c)

                cost[i][j] = best

        # DP over the number of parts.
        # dp[m][j] = min cost to split the first j characters into m semi-palindromes.
        dp = [[INF] * (n + 1) for _ in range(k + 1)]
        dp[0][0] = 0 # zero parts, zero characters: free

        for m in range(1, k + 1):
            # each part needs length >= 2, so m parts need at least 2*m characters
            for j in range(2 * m, n + 1):
                # i = where the previous m-1 parts end (exclusive).
                # the last part is s[i..j-1], which needs length >= 2, so i <= j-2
                for i in range(2 * (m - 1), j - 1):
                    if dp[m - 1][i] < INF:      # skip unreachable states
                        dp[m][j] = min(dp[m][j], dp[m - 1][i] + cost[i][j - 1])

        # give the final answer for the entire string into as many parts
        return dp[k][n]