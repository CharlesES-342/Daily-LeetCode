        # define a rolling hash function
        M = (1 << 61) - 1 # large prime keeps collision changce tiny
        B = random.randrange(10**6, M - 1)   # random base to resist anti-hash tests

        h = [0] * (n + 1) # hash of nums[0:i] (prefix hash)
        pw = [1] * (n + 1) # BASE ** i (mod M), required to cut off the left part

        for i, x in enumerate(nums):
            # append nums[i] with the running hash
            h[i + 1] = (h[i] * B + x) % M
            pw[i + 1] = pw[i] * B % M

        # check for a fixed length window
        def has_unique(L):
            """Return True if some subarray of this length appears exactly once."""
            pL = pw[L]
            # hash of nums[start: start+length] computed in O(1)
            #   entire nums[0:start+length] - nums[0:start]
            cnt = Counter(
                (h[i + L] - h[i] * pL) % M for i in range(n - L + 1)
            )
            # count of 1 means it is unique
            return any(c == 1 for c in cnt.values())

        # Binary Search for the answer
        lo, hi = 1, n # pointers
        while lo < hi:
            mid = (lo + hi) // 2
            if has_unique(mid):
                # the mid length works, look shorter
                hi = mid
            else:
                # mid length fails, look longer
                lo = mid + 1
        return lo

