# 3970. Shortest Path With At Most K Consecutive Identical Characters

# You are given an integer n representing the number of nodes in a directed weighted graph, numbered from 0 to n - 1. This is represented by a 2D integer array edges, where edges[i] = [ui, vi, wi] represents a directed edge from node ui to node vi with weight wi.
# You are also given a string labels of length n, where labels[i] is the character assigned to node i, and an integer k.
# Return the minimum total edge weight of a path from node 0 to node n - 1 such that the concatenation of the labels of the nodes along the path contains at most k consecutive identical characters. If no valid path exists, return -1.

# Example 1:
# Input: n = 3, edges = [[0,1,1],[1,2,1],[0,2,3]], labels = "aab", k = 1
# Output: 3
# Explanation:
# The optimal valid path from node 0 to node 2 is as follows:
# Use edges[2] = [0, 2, 3] to reach node 2 with a weight wi = 3.
# The corresponding concatenation of labels is "ab", which satisfies at most k = 1 consecutive identical characters. Thus, the answer is 3.

# Example 2:
# Input: n = 3, edges = [[0,1,1],[1,2,1],[0,2,3]], labels = "aab", k = 2
# Output: 2
# Explanation:
# The optimal valid path from node 0 to node 2 is as follows:
# Use edges[0] = [0, 1, 1] to reach node 1 with weight wi = 1.
# Use edges[1] = [1, 2, 1] to reach node 2 with weight wi = 1.
# The corresponding concatenation of labels is "aab", which satisfies at most k = 2 consecutive identical characters. Thus, the answer is 2.

# Example 3:
# Input: n = 3, edges = [[0,1,1],[1,2,1]], labels = "aaa", k = 2
# Output: -1
# Explanation:
# There is no valid path from node 0 to node 2 that satisfies at most k = 2 consecutive identical characters. Thus, the answer is -1.

# Constraints:
# 1 <= n == labels.length <= 5 * 104
# 0 <= edges.length <= 5 * 104
# edges[i] == [ui, vi, wi]
# 0 <= ui, vi <= n - 1
# ui != vi
# 1 <= wi <= 104
# labels consists of lowercase English letters
# 1 <= k <= 50


import heapq

class Solution(object):
    def shortestPath(self, n, edges, labels, k):
        """
        :type n: int
        :type edges: List[List[int]]
        :type labels: str
        :type k: int
        :rtype: int
        """
        # Build adjacency list: u -> list of (v, weight)
        adj = [[] for _ in range(n)]
        for u, v, w in edges:
            adj[u].append((v, w))
            
        # Min-heap stores: (total_weight, current_node, current_consecutive_count)
        # Starting at node 0. The initial count for labels[0] is 1.
        pq = [(0, 0, 1)]
        
        # Dictionary to track the minimum weight to reach a given (node, count) state
        best = {}
        
        while pq:
            w, u, count = heapq.heappop(pq)
            
            # If we reached the destination node, return the accumulated weight
            if u == n - 1:
                return w
                
            # If we've already found a cheaper way to reach this exact state, skip
            if best.get((u, count), float('inf')) < w:
                continue
                
            for v, weight in adj[u]:
                # Calculate the new consecutive count based on the label of node v
                if labels[v] == labels[u]:
                    new_count = count + 1
                else:
                    new_count = 1
                    
                # If the count exceeds k, abandon this route entirely
                if new_count > k:
                    continue
                    
                next_w = w + weight
                
                # If this path to state (v, new_count) is better, record it and push to heap
                if next_w < best.get((v, new_count), float('inf')):
                    best[(v, new_count)] = next_w
                    heapq.heappush(pq, (next_w, v, new_count))
                    
        return -1

